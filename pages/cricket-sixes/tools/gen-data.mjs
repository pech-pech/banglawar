// Generates js/data/match.js and js/data/ability.js from NUMBERS' tuning.json (no hand-typed numbers).
// Usage: node tools/gen-data.mjs /path/to/tuning.json
import { readFileSync, writeFileSync } from 'node:fs';
const t = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const { status, source, ...T } = structuredClone(t.match.T);
// Merge match.game_overrides on top of T. Dotted keys ("W_INT.A") set one leaf; plain-object values (W_INT, G5) are deep-merged so
// sibling keys survive (the file lists both "W_INT.A" and "W_INT": {A}). The "note" entry is prose. G5 keys use field_hybrid.json names:
// HY_KB->KB, HY_KW->KW, HY_WK->WK, HY_LATE->LATE, W_FIELD_A->W_A (combo_sim.FIELDS), per the note in the file.
const isObj = (v) => v && typeof v === 'object' && !Array.isArray(v);
const merge = (dst, src) => { for (const [k, v] of Object.entries(src)) { if (isObj(v) && isObj(dst[k])) merge(dst[k], v); else dst[k] = structuredClone(v); } };
const G5_NAMES = { HY_KB: 'KB', HY_KW: 'KW', HY_WK: 'WK', HY_LATE: 'LATE', P_C: 'P_C', W_FIELD_A: 'W_A' };
for (const [path, o] of Object.entries(t.match.game_overrides || {})) {
  if (path === 'note') continue;
  let val = (o && typeof o === 'object' && 'value' in o) ? o.value : o;
  if (path === 'G5') {
    const g = {};
    for (const [k, v] of Object.entries(val)) { if (k === 'existing_unchanged') continue; if (!(k in G5_NAMES)) throw new Error('unknown G5 key ' + k); g[G5_NAMES[k]] = v; }
    val = g;
  }
  const ks = path.split('.'); let n = T;
  for (const k of ks.slice(0, -1)) n = n[k] ??= {};
  const last = ks.at(-1);
  if (isObj(val) && isObj(n[last])) merge(n[last], val); else n[last] = structuredClone(val);
}
const grid = {};
for (const g of t.match.pairing_grid.grid) grid[`${g.bat}|${g.bowl}`] = g.batter_mod_steps;
const head = '// GENERATED by tools/gen-data.mjs from games-design/cricket-sixes/2026-11-12/data/tuning.json. Do not edit by hand.\n';
writeFileSync('js/data/match.js', head + `// status: simulated (match_sim.py)\nexport const T = ${JSON.stringify(T)};\nexport const MATCH = ${JSON.stringify(grid)};\nexport const BAT_HOME = ${JSON.stringify(t.match.home_phase.bat)};\nexport const BOWL_HOME = ${JSON.stringify(t.match.home_phase.bowl)};\nexport const CLAMPS = ${JSON.stringify(t.reference.ball_vectors.clamps)};\n`);
const a = t.ability, p = a.potential;
const out = { weights: a.weights, previews: a.call_previews.by_grade, bands: p.bands, limit: p.limit.upper_P, spread: p.spread, centre: p.centre_params, start_bonus: p.start_bonus, scout_bonus: p.scout_bonus, superstar: { chance: p.superstar.chance_per_candidate, mean: 170, sd: 8 } };
writeFileSync('js/data/ability.js', head + `// status: ${JSON.stringify(a.status)}\nexport const ABILITY = ${JSON.stringify(out)};\n`);
console.log('ok', Object.keys(T).length, 'T keys;', Object.keys(grid).length, 'grid cells');
