// Generates js/data/season.js from NUMBERS' tuning.json (no hand-typed numbers for tuned values).
// Usage: node tools/gen-season-data.mjs [/path/to/tuning.json]   (run from the app root)
// Values that tuning.json does not hold are listed in `guesses` below and in the output, never hidden.
import { readFileSync, writeFileSync } from 'node:fs';
const path = process.argv[2] || '/mnt/project-files/games-design/cricket-sixes/2026-11-12/data/tuning.json';
const t = JSON.parse(readFileSync(path, 'utf8'));
const L1 = t.ladder.leagues.list[0];
const S = t.ladder.season;
const TP = t.training.training_points;
if (!(L1.rival_avg > 0) || S.teams !== 10 || S.league_matches !== 9 || S.finals_teams !== 4) throw new Error('tuning.json season shape changed');

const out = {
  status: 'simulated for tuned values; guess for the keys in `guesses`',
  source: '2026-11-12/data/tuning.json ladder.leagues.list[0], ladder.leagues.rival_rating_sd, ladder.season, training.training_points, ability.potential.start_bonus; CONTRACT m0 s3, s9',
  teams: S.teams, leagueMatches: S.league_matches, finalsTeams: S.finals_teams, maxMatches: S.max_matches,
  points: { win: 2, tie: 1, loss: 0 }, // CONTRACT m0 "Settled for TEST-PLAN"
  league: { number: L1.number, ratingMean: L1.rival_avg, ratingSd: t.ladder.leagues.rival_rating_sd },
  tp: { perMatch: TP.per_match, perWin: TP.per_win, semiLoser: TP.finals.semi_loser, runnerUp: TP.finals.runner_up, champion: TP.finals.champion, leagueMultiplier: TP.league_multiplier },
  startBonus: t.ability.potential.start_bonus, // M's squad potentials roll +20 (CONTRACT m0 s3)
  squadSize: 10, sixSize: 6, // CONTRACT m0 question 1 default
  roles: { Opener: 3, Middle: 4, Lower: 3 }, types: { Fast: 4, Medium: 3, Spin: 3 },
  capRoom: 12, // CONTRACT s11: cap sum >= rating sum + 12
  clubOffsets: [-6, -4, -3, -1, 0, 1, 3, 4, 6], // mean offsets of the 9 AI clubs, shuffled per game
  myDrills: { full: 5, bench: 2, benchCount: 2 }, // CONTRACT m0 open point 3
  aiGrowth: 4, // CONTRACT m0 open point 9
  guesses: ['clubOffsets', 'roles', 'types', 'aiGrowth', 'myDrills', 'squadSize'],
};
const head = '// GENERATED by tools/gen-season-data.mjs from games-design/cricket-sixes/2026-11-12/data/tuning.json. Do not edit by hand.\n';
writeFileSync('js/data/season.js', head + `// status: ${out.status}\n// source: ${out.source}\nexport const SEASON = ${JSON.stringify(out, null, 1)};\n`);
console.log('ok season data written, league', L1.number, 'mean', L1.rival_avg);
