// Independent checker: beam search at 3-tick granularity, depth<=5 inputs.
(function(){
const fs=require('fs'),vm=require('vm'),path=require('path');
const P=path.join(__dirname,'..','parts');
for(const f of ['core','rooms','tpl1','tpl2']) vm.runInThisContext('(function(){'+fs.readFileSync(path.join(P,f+'.js'),'utf8')+'\n})()',{filename:f});
const PL=globalThis.PL, C=PL.C;
function clone(s){const o=Object.assign({},s);o.pending=s.pending?{...s.pending}:null;o.crumbleS=s.crumbleS.map(c=>({...c}));
  for(const k in s){const v=s[k];if(Array.isArray(v)&&k!=='crumbleS'&&k!=='room')o[k]=v.slice();}o.events=[];return o;}
const ACTS=[null,{k:'flip',dir:0},{k:'flip',dir:1},{k:'flip',dir:2},{k:'flip',dir:3},{k:'dive'}];
const SLOT=3, MAXT=25*120;
function key(s,n){const r=(v,q)=>Math.round(v/q);return [r(s.x,4),r(s.y,4),r(s.vx,25),r(s.vy,25),s.g,s.charges,s.grounded?1:0,n,s.crumbleS.map(c=>c.st).join('')].join(',')}
function search(room,{maxIn=5,W=250,stopFirst=true}={}){
  let layer=[{s:PL.newState(room),log:[],n:0}];let best=null;
  for(let slot=0;slot*SLOT<MAXT&&layer.length;slot++){
    const next=new Map();
    for(const nd of layer){
      for(let ai=0;ai<ACTS.length;ai++){
        const a=ACTS[ai]; if(a&&nd.n>=maxIn)continue;
        if(a&&a.k==='flip'&&a.dir===nd.s.g)continue;
        const s=clone(nd.s);const t0=s.t;let dead=false;
        for(let i=0;i<SLOT;i++){PL.step(s,i===0&&a?[a]:[]);if(s.dead>0){dead=true;break}if(s.won)break;}
        if(dead)continue;
        const n=nd.n+(a?1:0);const log=a?nd.log.concat([{tick:t0,k:a.k,dir:a.dir}]):nd.log;
        if(s.won){if(!best||s.t<best.t)best={t:s.t,log,n};if(stopFirst)return best;continue}
        const k=key(s,n);const sc=Math.hypot(s.x-room.exit.x,s.y-room.exit.y)+n*8+(s.grounded?0:0);
        const o=next.get(k);if(!o||sc<o.sc)next.set(k,{s,log,n,sc});
      }
    }
    layer=[...next.values()].sort((a,b)=>a.sc-b.sc).slice(0,W);
    if(best)return best;
  }
  return best;
}
function segHitsRect(a,b,r){for(let i=0;i<=40;i++){const x=a.x+(b.x-a.x)*i/40,y=a.y+(b.y-a.y)*i/40;if(x>=r[0]&&x<=r[0]+r[2]&&y>=r[1]&&y<=r[1]+r[3])return true}return false}
if(process.env.PROBE){module.exports={search,PL};return}
const rows=[],probs=[];
function checkRoom(tpl,mir,seed){
  const rng=PL.mulberry32(seed*7919+13);let room=tpl.make(rng);if(mir)room=PL.mirrorRoom(room);
  let r=search(room);
  if(!r)r=search(room,{W:600});
  return {room,r};
}
const hasCr=t=>t.make(PL.mulberry32(1)).crushers.length>0;
for(const tpl of PL.TEMPLATES){
  const cr=hasCr(tpl);const seeds=cr?[1,2,3,4,5]:[1];
  let fast=Infinity,fails=0,maxIn=0,triv=false,tn=0;
  for(const mir of [0,1])for(const sd of seeds){
    const {room,r}=checkRoom(tpl,mir,sd);tn++;
    if(!r){fails++;probs.push(`${tpl.id} mir=${mir} seed=${sd}: NO solution found (beam W600, <=5 inputs, <=25s)`);continue}
    fast=Math.min(fast,r.t/120);maxIn=Math.max(maxIn,r.n);
    if(sd===seeds[0]){ // trivial test: <=1 input
      const one=search(room,{maxIn:1,W:400});
      const line=[...room.spikes.map(s=>s.r),...room.crushers.map(c=>c.r)].some(rc=>segHitsRect(room.start,room.exit,rc));
      if(one&&one.n<=1&&!line){triv=true;probs.push(`${tpl.id} mir=${mir}: TRIVIAL (clears with ${one.n} input(s), ${(one.t/120).toFixed(1)}s, no hazard on start-exit line)`)}
      else if(one&&one.n<=1)probs.push(`${tpl.id} mir=${mir}: note: clears with ${one.n} input(s) (${(one.t/120).toFixed(1)}s) but hazard on line`);
    }
    // determinism replay
    const rp=PL.replay(room,r.log);if(!rp.state.won)probs.push(`${tpl.id} mir=${mir} seed=${sd}: beam log does not replay to win via PL.replay (state.won=false)`);
  }
  rows.push({id:tpl.id,tier:tpl.tier,teach:tpl.teach,cr,runs:tn,fails,fast,maxIn,triv});
  process.stderr.write(tpl.id+' fast='+fast.toFixed(2)+' fails='+fails+'\n');
}
// shaft
let shaftProb=[];
for(let sd=1;sd<=40;sd++){
  const sh=PL.buildShaft(sd,7);const ids=sh.map(r=>r.templateId);
  if(sh.length!==7||new Set(ids).size!==7){shaftProb.push(`seed ${sd}: ids ${ids.join(',')} not 7 distinct`);continue}
  const tiers=ids.map(i=>PL.TEMPLATES.find(t=>t.id===i).tier);
  if(tiers.some((t,i)=>i&&t<tiers[i-1]))shaftProb.push(`seed ${sd}: tiers not ascending ${tiers}`);
  if(JSON.stringify(PL.buildShaft(sd,7))!==JSON.stringify(sh))shaftProb.push(`seed ${sd}: not deterministic`);
  sh.forEach((room,i)=>{const r=search(room)||search(room,{W:600});if(!r)shaftProb.push(`seed ${sd} room ${i} (${room.templateId}${room.mirrored?' mirrored':''}): unsolvable by beam`)});
}
const tot=PL.TEMPLATES.length;
let md=`# Template review (independent beam-search checker)\nGenerated by src/test/shaft-check.js: beam search (width 250, retry 600), inputs at 3-tick slots, none/flip x4/dive, <=5 inputs, <=25 s. Templates found: ${tot}.\n\n| id | tier | crusher | runs | unsolved | fastest clear (s) | max inputs used | trivial |\n|---|---|---|---|---|---|---|---|\n`;
for(const r of rows)md+=`| ${r.id} | ${r.tier} | ${r.cr?'y':'n'} | ${r.runs} | ${r.fails} | ${isFinite(r.fast)?r.fast.toFixed(2):'-'} | ${r.maxIn} | ${r.triv?'TRIVIAL':'no'} |\n`;
md+=`\n## Shaft check (seeds 1..40, n=7)\n${shaftProb.length?shaftProb.map(x=>'- '+x).join('\n'):'All 40 seeds: 7 distinct templates, tier-ascending, deterministic, all rooms solvable.'}\n\n## Per-template findings and fixes\n${probs.length?probs.map(x=>'- '+x).join('\n'):'None.'}\n`;
fs.writeFileSync(path.join(__dirname,'..','review','templates.md'),md);
console.log(md);
})();
